/** Polish plural for day-count copy ("1 dzień", "2 dni", "5 dni", "dnia/dni"). */
const plural = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one;
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
};

