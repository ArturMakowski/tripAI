/** "a, b and c" / "a, b i c" */
const list = (lang: Lang, xs: string[]) =>
  xs.length < 2 ? (xs[0] ?? "") : `${xs.slice(0, -1).join(", ")} ${lang === "pl" ? "i" : "and"} ${xs[xs.length - 1]}`;

